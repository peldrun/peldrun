# ---------------------------------------------------------------------------
# Image search observation parsing (agent mode)
# ---------------------------------------------------------------------------
#
# In agent mode, image_search runs as a core tool and its result arrives
# here as a stringified OBSERVATION event. The structured image metadata
# (image_url, thumbnail_url, width, height) is not carried through the
# event payload, so we re-extract it by parsing the tool's deterministic
# markdown output.
#
# The output format is generated by peldrun/tools/builtins/image_search.py:
#
#   ## Image Search Results for 'QUERY'
#   *(via PROVIDER | N image(s) | Xms | est. $Y)*
#
#   1. **TITLE** (WxH)
#      - **Image URL:** https://...
#      - **Thumbnail:** https://...
#      - **Source Page:** https://...
#      - **Host:** example.com
#
#   2. **TITLE2** ...
#
# Parsing is best-effort: if the format changes, only the gallery
# preview is affected - the agent still sees the full text observation.

import re as _re

_IMAGE_HEADER_RE = _re.compile(
    r"##\s+Image Search Results for\s+'(?P<query>.+?)'",
    _re.IGNORECASE,
)

_IMAGE_PROVIDER_RE = _re.compile(
    r"\*\(via\s+(?P<provider>[^|]+?)\s*\|",
    _re.IGNORECASE,
)

_IMAGE_ENTRY_RE = _re.compile(
    r"^\d+\.\s+\*\*(?P<title>.+?)\*\*"
    r"(?:\s+\((?P<width>\d+)x(?P<height>\d+)\))?"
    r"\n\s+-\s+\*\*Image URL:\*\*\s+(?P<image_url>\S+)"
    r"(?:\n\s+-\s+\*\*Thumbnail:\*\*\s+(?P<thumb_url>\S+))?"
    r"(?:\n\s+-\s+\*\*Source Page:\*\*\s+(?P<source_url>\S+))?"
    r"(?:\n\s+-\s+\*\*Host:\*\*\s+(?P<host>\S+))?",
    _re.MULTILINE,
)


def _parse_image_search_observation(text: str) -> List[Dict[str, Any]]:
    """
    Extract structured image records from image_search's markdown output.
    Returns an empty list when the text does not look like image results.

    Detection is header-based (``## Image Search Results``) rather than
    marker-based so that future per-entry field changes — e.g. adding
    ``Local Image Path`` after ``Image URL`` when auto_download is on —
    do not silently break the gallery. The regex itself returns [] if
    it cannot extract at least one entry, which safely no-ops on any
    observation that does not carry image data.
    """
    if not text or "## Image Search Results" not in text:
        return []

    out: List[Dict[str, Any]] = []
    for match in _IMAGE_ENTRY_RE.finditer(text):
        title = (match.group("title") or "").strip()
        image_url = (match.group("image_url") or "").strip()
        if not title or not image_url:
            continue

        thumb = (match.group("thumb_url") or "").strip()
        src_page = (match.group("source_url") or "").strip()
        src_host = (match.group("host") or "").strip()

        def _to_int(v: Optional[str]) -> Optional[int]:
            if not v:
                return None
            try:
                n = int(v)
                return n if n > 0 else None
            except (TypeError, ValueError):
                return None

        out.append(
            {
                "title": title,
                "image_url": image_url,
                "thumbnail_url": thumb or None,
                "source_url": src_page or None,
                "width": _to_int(match.group("width")),
                "height": _to_int(match.group("height")),
                "source": src_host or None,
            }
        )

    return out


def _is_proxy_url(url: str) -> bool:
    """
    Return True when the URL is already a PELDRUN image-proxy link.

    ``image_search.py`` emits proxied URLs in ``**Image URL:**`` (so
    the agent can download via the proxy). By the time the parser runs
    here, we must detect this case and NOT re-wrap the URL — doing so
    would produce ``/api/search/image-proxy?url=http://127.0.0.1:8088/
    api/search/image-proxy?...`` which the SSRF guard correctly rejects
    (127.0.0.1 is a private host).
    """
    return bool(url) and isinstance(url, str) and "/api/search/image-proxy" in url


def _extract_proxy_path(url: str) -> str:
    """
    Extract the ``/api/search/image-proxy?...`` portion from a full
    proxy URL (e.g. ``http://127.0.0.1:8088/api/search/image-proxy?
    url=...``). Returns the URL unchanged when no proxy path is found.

    Returning the relative path (not the absolute URL) keeps the
    frontend portable: the browser resolves it against the current
    origin, which works via the next.js ``/api/*`` rewrite regardless
    of whether the app is loaded from ``localhost``, a LAN IP, or a
    reverse-proxied hostname.
    """
    if not url:
        return url
    idx = url.find("/api/search/image-proxy")
    if idx >= 0:
        return url[idx:]
    return url


def _extract_query_from_observation(text: str) -> Optional[str]:
    m = _IMAGE_HEADER_RE.search(text)
    return m.group("query").strip() if m else None


def _extract_provider_from_observation(text: str) -> Optional[str]:
    m = _IMAGE_PROVIDER_RE.search(text)
    return m.group("provider").strip() if m else None


# ---------------------------------------------------------------------------
# Tool-call leak detection
# ---------------------------------------------------------------------------
#
# A "tool-call leak" occurs when the model emits the SYNTAX of a tool
# call as PLAIN TEXT in the final response, instead of invoking the
# tool. This happens most often with:
#
#   * Small or quantized models that confuse the "I should call
#     terminate" intent with "I should write 'terminate(...)' as my
#     message."
#   * Models recovering from an INCOMPLETE_STREAM: the retry path in
#     ``ToolCallAgent`` may produce only a partial tool-call fragment
#     as ``response.content``.
#   * Models that hallucinate the ``terminate`` tool before it is
#     registered and fall back to echoing the syntax.
#
# The result of the leak is that ``run_result.output`` contains
# something like:
#
#     terminate(status="success", message="
#
# or
#
#     done()
#
# — which is not a human-readable answer, and which visually REPLACES
# the real content the model streamed earlier in the turn.
#
# The regex below is intentionally conservative:
#   * Anchored with ``^`` — only a response that STARTS with the
#     syntax is flagged. A legitimate answer that happens to mention
#     "call terminate(...) at the end" is not affected.
#   * Length-capped at 500 chars — a real answer that starts with the
#     tool name and continues with 2KB of prose is not flagged. Only
#     short leaks (which are always malformed fragments) are caught.
#   * Case-insensitive so ``TERMINATE(`` / ``Terminate(`` also match.
#   * The ``done`` alternative is included for backward compatibility
#     with the pre-B3 name.
_TOOL_CALL_LEAK_RE = _re.compile(
    r"^\s*(?:call\s+)?(?:terminate|done)\s*\(",
    _re.IGNORECASE,
)

# Maximum length of a string that can still be classified as a
# tool-call leak. Longer strings are assumed to be prose (a real
# answer that happens to start with the tool name).
_TOOL_CALL_LEAK_MAX_LEN = 500


def _looks_like_tool_call_leak(text: Optional[str]) -> bool:
    """Return True if ``text`` looks like leaked tool-call syntax.

    See the module-level comment above for the full rationale, the
    failure modes this detector closes, and the reasons for each
    constraint in the regex.
    """
    if not text or not isinstance(text, str):
        return False
    stripped = text.strip()
    if not stripped:
        return False
    if len(stripped) > _TOOL_CALL_LEAK_MAX_LEN:
        return False
    return bool(_TOOL_CALL_LEAK_RE.match(stripped))


# ---------------------------------------------------------------------------
# Trailing tool-call leak stripper
# ---------------------------------------------------------------------------
#
# A DIFFERENT failure mode from the one `_looks_like_tool_call_leak`
# addresses: the model writes a full, useful summary, THEN appends a
# trailing "Now calling terminate as requested." sentence followed by
# a JSON code block, THEN separately invokes the tool as a real call.
#
# This is the exact shape GigaChat-3-Pro produces when the model
# transitions from "answering" mode to "calling a tool" mode. The
# JSON block is not actionable — the real tool call already happened —
# but if it leaks into the final answer bubble, the user sees raw
# JSON at the bottom of an otherwise-good response.
#
# Observed shape:
#
#     All three files have been created in the current directory:
#     ... (a real, useful summary) ...
#
#     Now calling terminate as requested.
#
#     ```json
#     {
#       "status": "success",
#       "message": "..."
#     }
#     ```
#
# The regex is INTENTIONALLY narrow: it requires the "Now calling /
# invoking / using <tool> [as requested]" preface. A legitimate answer
# that happens to end with a JSON code block (e.g. "Here is the JSON
# schema we use:\n```json\n{...}\n```") is NOT touched — there is no
# "Now calling..." sentence preceding it.
_TRAILING_TOOL_CALL_BLOCK_RE = _re.compile(
    r"\n+\s*"
    r"(?:Now\s+(?:I\s+(?:will|am\s+going\s+to)\s+)?"
    r"(?:calling|invoking|using)|"
    r"Calling|Invoking|Using)\s+[\w.]+\s+"
    r"(?:as\s+requested\.?|now\.?)?\s*"
    r"```(?:json)?\s*\{[^`]*?\}\s*```\s*$",
    _re.IGNORECASE | _re.DOTALL,
)


def _strip_trailing_tool_call_block(text: Optional[str]) -> str:
    """Remove a trailing "Now calling X..." + JSON block from ``text``.

    Returns ``text`` unchanged (after rstrip) when the pattern is not
    present, so a legitimate answer that happens to end with a JSON
    example cannot be corrupted.

    See the regex comment above for the exact shape this targets.
    """
    if not text or not isinstance(text, str):
        return text or ""
    stripped = _TRAILING_TOOL_CALL_BLOCK_RE.sub("", text)
    return stripped.rstrip()


def _collect_specialist_tool_allowlists(
    enabled_tool_ids: Set[str],
) -> Dict[str, List[str]]:
    """Build a mapping of specialist agent IDs to their effective tool IDs.

    Uses ``get_agent_tools_state`` so user-saved tool overrides
    (disabled_tools / extra_tools) are honoured when an agent delegates
    to a specialist. Falls back to the raw manifest ``tools`` field if
    the effective lookup fails for any agent, so a corrupted settings
    file cannot break delegation discovery.
    """
    specialist_map: Dict[str, List[str]] = {}
    try:
        from omweb.agents.registry import agent_registry

        agents_list: List[Dict[str, Any]] = []
        if hasattr(agent_registry, "list_agents") and callable(agent_registry.list_agents):
            agents_list = list(agent_registry.list_agents() or [])

        for ag in agents_list:
            if not isinstance(ag, dict):
                continue
            ag_id = str(ag.get("id") or "").strip().lower()
            if not ag_id:
                continue

            # Prefer the effective tool list so overrides are honoured.
            tools_source: List[str] = []
            try:
                state = agent_registry.get_agent_tools_state(ag_id)
                tools_source = list(state.get("effective_tools") or [])
            except Exception:
                raw_tools = ag.get("tools")
                tools_source = list(raw_tools) if isinstance(raw_tools, list) else []

            # MCP tool identifiers (``mcp__server__tool`` or
            # ``mcp::server::tool``) must always pass through to the
            # coordinator, because they are not registered in the Web
            # tool registry (`enabled_tool_ids`). The coordinator
            # resolves them at delegation time via `resolve_tool_runtime`
            # → MCP session pool. Filtering on `enabled_tool_ids` alone
            # would silently strip every MCP tool from delegated
            # children.
            filtered: List[str] = []
            seen_specialist_tools: Set[str] = set()
            for raw_t in tools_source:
                t = str(raw_t).strip()
                if not t or t in ("terminate", "delegate_task", "delegate"):
                    continue
                if t in enabled_tool_ids or t.startswith(("mcp__", "mcp::")):
                    if t not in seen_specialist_tools:
                        seen_specialist_tools.add(t)
                        filtered.append(t)

            # ── Expand the specialist's declared MCP servers ─────
            # ``mcp_servers`` on a manifest is a list of *server* ids
            # (e.g. ``["filesystem"]``), not tool ids. Materialise each
            # into the concrete tools it exposes so the coordinator can
            # forward them to the child. We read from the per-server
            # tool cache populated during the parent's run phase (which
            # executes BEFORE this function, so the cache is warm).
            # Cold-cache servers are skipped silently — their tools
            # will be resolved lazily on first invocation by the
            # server-ID expansion path in ``resolve_authorized_tools``.
            try:
                from omweb.extensions.mcp_pool import mcp_session_pool

                effective_manifest = agent_registry.get_effective_agent(ag_id)
                declared_servers = list(
                    effective_manifest.get("effective_mcp_servers")
                    or effective_manifest.get("mcp_servers")
                    or []
                )
                for srv_id in declared_servers:
                    sid = str(srv_id).strip()
                    if not sid:
                        continue
                    cached_tools = mcp_session_pool.get_cached_tools(sid)
                    if not cached_tools:
                        continue
                    for tool_info in cached_tools:
                        remote_name = tool_info.get("name")
                        if not remote_name:
                            continue
                        expanded = f"mcp__{sid}__{remote_name}"
                        if expanded not in seen_specialist_tools:
                            seen_specialist_tools.add(expanded)
                            filtered.append(expanded)
            except Exception as expansion_exc:
                logger.debug(
                    "Specialist MCP server expansion for '%s' skipped: %s",
                    ag_id,
                    expansion_exc,
                )

            specialist_map[ag_id] = filtered
    except Exception as exc:
        logger.debug("Specialist tool allowlist discovery notice: %s", exc)

    return specialist_map


# ---------------------------------------------------------------------------
# MCP per-chat authentication helpers
# ---------------------------------------------------------------------------
#
# The engine no longer enforces MCP auth eagerly. It resolves whatever
# per-chat credentials the user has ALREADY recorded so that tool
# discovery works with the correct auth context, and defers enforcement
# to the MCP tool executor in resolve_tool_runtime.py — see
# _mcp_tool_executor. That design makes "hi" work without opening the
# auth modal, while still prompting correctly the moment the agent
# actually tries to use an MCP tool.
#
# The helper below is pure and side-effect free. All SSE emission,
# job-failure signalling, and run cancellation live in:
#   * omweb.extensions.mcp_auth_state   (state registry)
#   * omweb.adapters.core_adapter_parts.resolve_tool_runtime (lazy gate)
# ---------------------------------------------------------------------------


def _resolve_mcp_env_optional(
    *,
    chat_id: str,
    server_id: str,
) -> Optional[Dict[str, str]]:
    """
    Return the per-chat env override for an MCP server, or None.

    Unlike `_ensure_mcp_auth`, this function has NO side effects: it
    does not emit SSE events, does not fail the job, and does not
    raise. It simply reports what credentials (if any) the user has
    already recorded for this chat.

    Used only for tool *discovery* so the agent sees the correct
    tool list. Auth enforcement happens lazily inside the MCP tool
    executor at invocation time.

    Returns:
      * The env dict (with OAuth meta-keys when applicable) if the
        user recorded "custom" or "ephemeral" credentials.
      * None if there is no decision, or the decision was "use_global"
        (the caller should then fall back to settings_manager).
    """
    from omweb.extensions.chat_mcp_auth import (
        MODE_CUSTOM,
        MODE_EPHEMERAL,
        get_chat_mcp_auth_store,
    )

    store = get_chat_mcp_auth_store()
    mode = store.get_mode(chat_id, server_id)

    if mode == MODE_CUSTOM:
        env = store.get_env(chat_id, server_id) or {}
        oauth = store.get_oauth_tokens(chat_id, server_id)
        if isinstance(oauth, dict) and oauth.get("access_token"):
            env = dict(env)
            env["_oauth_access_token"] = str(oauth["access_token"])
            env["_oauth_token_type"] = str(
                oauth.get("token_type") or "Bearer"
            )
        return env or None

    if mode == MODE_EPHEMERAL:
        env = store.get_ephemeral(chat_id, server_id) or {}
        oauth = store.get_ephemeral_oauth(chat_id, server_id)
        if isinstance(oauth, dict) and oauth.get("access_token"):
            env = dict(env)
            env["_oauth_access_token"] = str(oauth["access_token"])
            env["_oauth_token_type"] = str(
                oauth.get("token_type") or "Bearer"
            )
        return env or None

    return None


