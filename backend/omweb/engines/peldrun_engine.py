        collected_images_query: str = ""
        collected_images_provider: str = "unknown"

        def _extract_event_step(evt: PeldrunEvent) -> Optional[int]:
            if hasattr(evt, "step") and isinstance(evt.step, int) and evt.step > 0:
                return evt.step
            if hasattr(evt, "payload") and isinstance(evt.payload, dict):
                p_step = (
                    evt.payload.get("step")
                    or evt.payload.get("step_num")
                    or evt.payload.get("current_step")
                )
                if isinstance(p_step, int) and p_step > 0:
                    return p_step
                if isinstance(p_step, str) and p_step.isdigit() and int(p_step) > 0:
                    return int(p_step)
            return None

        async def _sync_and_dispatch_artifacts(step_num: int) -> List[str]:
            nonlocal event_seq
            current_files = _scan_workspace_files()
            discovered_paths: List[str] = []

            for rel_path, file_path in current_files.items():
                if rel_path not in known_artifact_paths:
                    known_artifact_paths.add(rel_path)
                    discovered_paths.append(rel_path)
                    file_name = file_path.name
                    file_size = file_path.stat().st_size

                    if rel_path not in job_scoped_artifacts[job_id]:
                        job_scoped_artifacts[job_id].append(rel_path)

                    if chat_id and rel_path not in job_scoped_artifacts[chat_id]:
                        job_scoped_artifacts[chat_id].append(rel_path)

                    event_seq += 1
                    print(f"[ENGINE PELDRUN] Detected Artifact Created on Disk: {rel_path} ({file_size} bytes)")

                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.ARTIFACT_CREATED,
                            step=step_num,
                            data={
                                "artifact": rel_path,
                                "path": rel_path,
                                "relative_path": rel_path,
                                "name": file_name,
                                "size_bytes": file_size,
                                "chat_id": chat_id,
                                "job_id": job_id,
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )

            return discovered_paths

        async def _process_single_core_event(event: PeldrunEvent) -> None:
            nonlocal latest_meaningful_thought, accumulated_content, current_core_step, is_first_step_start, event_seq
            nonlocal collected_proxied_images, collected_images_query, collected_images_provider

            event_seq += 1
            explicit_step = _extract_event_step(event)
            if explicit_step is not None:
                current_core_step = explicit_step
                is_first_step_start = False
            elif event.type == EventType.STEP_START:
                if is_first_step_start:
                    current_core_step = 1
                    is_first_step_start = False
                else:
                    current_core_step += 1

            curr_step = current_core_step

            if event.type == EventType.STEP_START:
                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.STEP_START,
                        step=curr_step,
                        data={
                            "step": curr_step,
                            "seq": event_seq,
                            "model": model_name,
                            "engine": self.engine_id,
                            "status": "running",
                        },
                    ),
                )

            elif event.type == EventType.THOUGHT or getattr(event.type, "name", "") == "STEP_PROGRESS":
                # [STREAMING-AGENT] Streaming deltas and full-thought events
                # share the same EventType.THOUGHT channel, discriminated by
                # ``is_delta`` in the payload. Deltas must NOT be stripped
                # (whitespace tokens like " " are semantically meaningful
                # for word boundaries), and must be accumulated into
                # ``latest_meaningful_thought`` rather than replacing it —
                # otherwise a fallback final message derived from this
                # variable would end up being the last single token.
                _thought_payload = (
                    event.payload
                    if isinstance(event.payload, dict)
                    else {}
                )

                # [FIX-THOUGHT-RESET] Handle the retry-reset sentinel
                # emitted by ``ToolCallAgent._emit_reset_events()``
                # BEFORE each retry attempt. Mirrors the CHUNK handler
                # above (Fix 2). The reset event carries no ``thought``
                # field, so the historical code dropped it on the
                # ``should_emit`` gate — leaving both the backend
                # accumulator and the frontend buffer with the failed
                # attempt's text.
                #
                # Consequences of dropping the reset on this channel:
                #   * ``latest_meaningful_thought`` kept the failed
                #     attempt's reasoning. When CHUNK also produced no
                #     content (the common INCOMPLETE_STREAM recovery
                #     path), the fallback final answer was synthesized
                #     from this STALE reasoning — showing the user
                #     partial output from a request that errored.
                #   * The frontend reasoning panel kept the failed
                #     attempt's text visible, then appended the retry's
                #     deltas on top → duplicated reasoning in the UI.
                #
                # New behavior: clear the accumulator locally AND
                # forward the reset to the frontend so both sides
                # restart from a clean slate, matching the CHUNK
                # channel contract.
                if _thought_payload.get("reset"):
                    latest_meaningful_thought = ""
                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.THOUGHT,
                            step=curr_step,
                            data={
                                "reset": True,
                                "attempt_id": _thought_payload.get(
                                    "attempt_id"
                                ),
                                "reason": _thought_payload.get(
                                    "reason", ""
                                ),
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )
                    return

                raw_thought = _thought_payload.get("thought", "")
                is_delta = bool(_thought_payload.get("is_delta"))
                thought_text = str(raw_thought)

                # For deltas: keep whitespace-only fragments.
                # For non-deltas: skip whitespace-only noise.
                should_emit = is_delta and thought_text != "" or (
                    not is_delta and thought_text.strip()
                )

                if should_emit:
                    if is_delta:
                        latest_meaningful_thought = (
                            (latest_meaningful_thought or "") + thought_text
                        )
                    else:
                        # [FIX-THOUGHT-NON-DELTA-OVERWRITE] A non-delta
                        # THOUGHT is a one-shot emission (the agent's
                        # fallback for the reasoning channel, or a
                        # ``STEP_PROGRESS`` event forwarded through
                        # this handler). The historical code assigned
                        # it unconditionally, which let a short
                        # fallback fragment wipe a large accumulated
                        # reasoning trace.
                        #
                        # This parallels the CHUNK channel's Fix 2 and
                        # uses the same rule: only accept the
                        # replacement when the incoming text is at
                        # least as long as what we already have, or
                        # when the accumulator is empty. A shorter
                        # replacement is almost always stale noise
                        # from a failed attempt.
                        if (
                            not latest_meaningful_thought
                            or len(thought_text)
                            >= len(latest_meaningful_thought)
                        ):
                            latest_meaningful_thought = thought_text
                        else:
                            logger.info(
                                "[ENGINE PELDRUN] Rejecting non-delta "
                                "THOUGHT for job %s: %d chars would "
                                "overwrite %d chars of already-"
                                "accumulated reasoning (preview: %r).",
                                job_id,
                                len(thought_text),
                                len(latest_meaningful_thought),
                                thought_text[:80],
                            )
                            return

                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.THOUGHT,
                            step=curr_step,
                            data={
                                "thought": thought_text,
                                "content": thought_text,
                                "is_delta": is_delta,
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )

            elif event.type == EventType.CHUNK:
                # Streaming content delta from the agent — the model's
                # user-visible output. Dispatched as SSEEventType.CHUNK
                # so the frontend renders it in the main response bubble
                # (finalResult) instead of the reasoning panel.
                _chunk_payload = (
                    event.payload
                    if isinstance(event.payload, dict)
                    else {}
                )

                # [FIX-CHUNK-RESET] Handle the retry-reset sentinel
                # emitted by ``ToolCallAgent._emit_reset_events()``
                # BEFORE each retry attempt.
                #
                # The historical handler dropped this event entirely:
                # the reset payload has no ``delta`` / ``text`` /
                # ``content`` field, so ``delta_text`` was "" and the
                # entire branch was skipped. Two consequences:
                #
                #   1. ``accumulated_content`` retained the failed
                #      attempt's text. When the retry produced a
                #      shorter / partial / malformed response, the
                #      accumulated buffer contained a STALE + FRESH
                #      concatenation that was neither attempt in
                #      isolation — corrupt text.
                #
                #   2. The frontend never saw the reset, so its local
                #      buffer kept the failed attempt's text visible.
                #      If the retry also streamed content, the user
                #      saw DUPLICATE text (failed attempt + retry
                #      attempt) in the same bubble.
                #
                # New behavior: clear the accumulator locally AND
                # forward the reset to the frontend so both sides
                # restart from a clean slate. The ``attempt_id`` is
                # preserved so the frontend can correlate the new
                # attempt's chunks with the reset marker.
                if _chunk_payload.get("reset"):
                    accumulated_content = ""
                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.CHUNK,
                            step=curr_step,
                            data={
                                "reset": True,
                                "attempt_id": _chunk_payload.get(
                                    "attempt_id"
                                ),
                                "reason": _chunk_payload.get(
                                    "reason", ""
                                ),
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )
                    return

                raw_delta = (
                    _chunk_payload.get("delta")
                    or _chunk_payload.get("text")
                    or _chunk_payload.get("content")
                    or ""
                )
                delta_text = str(raw_delta)
                is_delta = bool(_chunk_payload.get("is_delta"))
                if delta_text:
                    # Accumulate into `accumulated_content` so the final
                    # message reflects the streamed response even when
                    # `run_result.output` is empty or generic (e.g., when
                    # the agent terminates via the `terminate` tool
                    # without echoing the accumulated content back).
                    if is_delta:
                        accumulated_content = (
                            accumulated_content + delta_text
                        )
                    else:
                        # [FIX-NON-DELTA-OVERWRITE] A non-delta CHUNK
                        # is the agent's non-streaming fallback: the
                        # provider never streamed, so the agent emits
                        # the entire ``response.content`` in one shot.
                        #
                        # The historical ``accumulated_content =
                        # delta_text`` unconditionally REPLACED the
                        # accumulator. That is correct when the
                        # accumulator is empty (nothing was streamed —
                        # this IS the answer). It is catastrophic when:
                        #
                        #   * the previous attempt streamed a LARGE
                        #     answer (accumulator non-empty), AND
                        #   * the retry produced a SHORT / malformed
                        #     ``response.content`` (e.g. a bare
                        #     tool-call echo like
                        #     'terminate(status="success", message="').
                        #
                        # Real-world failure mode (job_4bc33f8fd493
                        # class): a large streamed answer was visible
                        # to the user, a retry fired, the retry's
                        # ``response.content`` contained only the
                        # tool-call fragment, and the fallback CHUNK
                        # overwrote the entire user-visible answer
                        # with that garbage. The user lost the answer
                        # they had already watched being generated.
                        #
                        # Rule: only accept the replacement when the
                        # incoming text is at least as long as what we
                        # already accumulated, OR when the accumulator
                        # is empty. A SHORTER fallback is almost always
                        # stale noise from a failed attempt — reject it
                        # at both the backend (do not update
                        # ``accumulated_content``) AND the frontend (do
                        # not dispatch), so the two sides stay in sync.
                        if (
                            not accumulated_content
                            or len(delta_text) >= len(accumulated_content)
                        ):
                            accumulated_content = delta_text
                        else:
                            logger.info(
                                "[ENGINE PELDRUN] Rejecting non-delta "
                                "CHUNK for job %s: %d chars would "
                                "overwrite %d chars of already-"
                                "accumulated content (preview: %r).",
                                job_id,
                                len(delta_text),
                                len(accumulated_content),
                                delta_text[:80],
                            )
                            return

                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.CHUNK,
                            step=curr_step,
                            data={
                                "delta": delta_text,
                                "text": delta_text,
                                "content": delta_text,
                                "is_delta": is_delta,
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )

            elif (
                event.type == getattr(EventType, "TOOL_CALL", None)
                or event.type == getattr(EventType, "TOOL_CALLED", None)
            ):
                tool_name = str(event.payload.get("tool_name") or event.payload.get("tool") or "tool")
                arguments = event.payload.get("arguments", {})
                raw_args = (
                    json.dumps(arguments, ensure_ascii=False)
                    if isinstance(arguments, dict)
                    else str(arguments)
                )

                # [RESOURCE-MONITOR-FIX] Open an ExecutionSpanModel for
                # this tool call. The corresponding end_span call fires
                # on the matching OBSERVATION event below. The span ID
                # is stored under tool_call_id (primary) and tool_name
                # (fallback) so parallel tool calls in one step close
                # correctly even when providers omit either field.
                _tc_id = str(event.payload.get("tool_call_id") or "")
                if _monitor is not None:
                    try:
                        _span_id = f"span_{uuid.uuid4().hex[:12]}"
                        _monitor.start_span(
                            span_id=_span_id,
                            run_id=job_id,
                            target_name=tool_name,
                            span_type=_SpanType.TOOL_CALL,
                        )
                        _span_key = _tc_id or tool_name
                        _active_tool_spans[_span_key] = _span_id
                        if _tc_id and _tc_id != tool_name:
                            # Also index by tool_name as secondary key
                            # so an OBSERVATION that carries only the
                            # name can still close the right span.
                            _active_tool_spans.setdefault(
                                tool_name, _span_id
                            )
                    except Exception as _sp_exc:
                        logger.debug(
                            "[RESOURCE-MONITOR] start_span failed for "
                            "tool %s (job %s): %s",
                            tool_name,
                            job_id,
                            _sp_exc,
                        )

                is_human_ask = tool_name in ("ask_human", "human_input")
                tool_call_payload: Dict[str, Any] = {
                    "name": tool_name,
                    "toolName": tool_name,
                    "arguments": raw_args,
                    "content": raw_args,
                    "seq": event_seq,
                    "model": model_name,
                    "requires_input": is_human_ask,
                }
                if is_human_ask and isinstance(arguments, dict):
                    tool_call_payload["prompt"] = (
                        arguments.get("prompt")
                        or arguments.get("query")
                        or arguments.get("question")
                        or ""
                    )
                    tool_call_payload["input_type"] = arguments.get("input_type", "text")
                    tool_call_payload["options"] = arguments.get("options", [])
                    req_id = arguments.get("request_id")
                    if (
                        not req_id
                        and hasattr(HumanInputRegistry, "_pending_requests")
                        and HumanInputRegistry._pending_requests
                    ):
                        req_id = list(HumanInputRegistry._pending_requests.keys())[-1]
                    if req_id:
                        tool_call_payload["request_id"] = req_id

                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.TOOL_CALL,
                        step=curr_step,
                        data=tool_call_payload,
                    ),
                )

            elif event.type == getattr(EventType, "TOOL_CALL_STARTING", None):
                # [TOOL_CALL_STARTING] Early signal that the model has
                # begun emitting a tool call. The arguments JSON is
                # still being streamed at this point (typically
                # 5-20 seconds before it is complete). Forwarding this
                # immediately lets the frontend display a
                # "⏳ preparing <tool_name>…" placeholder so the user
                # sees activity during what would otherwise be a
                # silent wait.
                #
                # This is NOT a replacement for TOOL_CALL — the real
                # event arrives later, once the framework has
                # assembled the complete tool_call payload. The
                # frontend replaces the pending placeholder at that
                # point.
                payload = event.payload if isinstance(event.payload, dict) else {}
                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.TOOL_CALL_STARTING,
                        step=curr_step,
                        data={
                            "tool_name": str(payload.get("tool_name", "")),
                            "tool_call_id": str(payload.get("tool_call_id", "")),
                            "seq": event_seq,
                            "model": model_name,
                        },
                    ),
                )

            elif event.type == getattr(EventType, "TOOL_OUTPUT", None):
                # Opt-in streaming: raw stdout/stderr chunks emitted by
                # tools that opted into the streaming contract. Forwarded
                # verbatim to the frontend, which appends them to the
                # matching tool card's live-output buffer.
                #
                # The payload shape mirrors the ToolOutputPayload schema
                # in peldrun.events.schema. Every field is forwarded as-
                # is; only `seq` (the SSE envelope sequence) and `model`
                # (informational) are added by this layer. Duplicate
                # filtering after an SSE reconnect is the frontend's
                # responsibility -- the reducer drops chunks whose
                # `sequence` is <= the last one it processed.
                #
                # The engine-level `streaming_enabled` check is defense
                # in depth: the agent should never emit these events when
                # the flag is off, but if it does (e.g. the flag was
                # flipped mid-run), dropping here keeps the frontend
                # consistent with the configured behavior.
                if streaming_enabled:
                    payload = event.payload if isinstance(event.payload, dict) else {}
                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.TOOL_OUTPUT,
                            step=curr_step,
                            data={
                                "tool_call_id": payload.get("tool_call_id", ""),
                                "tool_name": payload.get("tool_name", ""),
                                "stream": payload.get("stream", "stdout"),
                                "chunk": payload.get("chunk", ""),
                                "sequence": payload.get("sequence", 0),
                                "attempt": payload.get("attempt", 1),
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )

            elif event.type == getattr(EventType, "TOOL_PROGRESS", None):
                # Opt-in structured progress updates. Same envelope and
                # deduplication contract as TOOL_OUTPUT, but the payload
                # carries current/total/phase instead of `stream`.
                # `stream` is deliberately omitted: for progress events
                # the discriminator is the event type itself, and
                # including `stream="progress"` would duplicate that
                # information in a place the frontend does not read.
                if streaming_enabled:
                    payload = event.payload if isinstance(event.payload, dict) else {}
                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.TOOL_PROGRESS,
                            step=curr_step,
                            data={
                                "tool_call_id": payload.get("tool_call_id", ""),
                                "tool_name": payload.get("tool_name", ""),
                                "chunk": payload.get("chunk", ""),
                                "sequence": payload.get("sequence", 0),
                                "attempt": payload.get("attempt", 1),
                                "current": payload.get("current"),
                                "total": payload.get("total"),
                                "phase": payload.get("phase"),
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )

            elif event.type == EventType.ASK_HUMAN:
                payload = event.payload if isinstance(event.payload, dict) else {}
                prompt_text = payload.get("prompt") or payload.get("question") or ""
                req_id = payload.get("request_id") or ""
                tool_call_payload = {
                    "name": "ask_human",
                    "toolName": "ask_human",
                    "prompt": prompt_text,
                    "question": prompt_text,
                    "input_type": payload.get("input_type", "text"),
                    "options": payload.get("options", []),
                    "request_id": req_id,
                    "requires_input": True,
                    "seq": event_seq,
                    "model": model_name,
                }
                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.TOOL_CALL,
                        step=curr_step,
                        data=tool_call_payload,
                    ),
                )

            elif (
                event.type == EventType.OBSERVATION
                or event.type == getattr(EventType, "TOOL_COMPLETED", None)
            ):
                obs_out = event.payload.get("output", "") or event.payload.get("error", "")

                # Serialize structured tool outputs as JSON, not as
                # Python `repr`. `str({"approval_id": "x"})` produces
                # "{'approval_id': 'x'}" (single quotes, Python repr),
                # which `JSON.parse` on the frontend rejects. In
                # practice peldrun-core often stringifies tool outputs
                # BEFORE this bridge sees them, so a plain string can
                # still be a Python repr. Handle both shapes:
                #
                #   - dict / list          -> json.dumps
                #   - string beginning "{"/"[" -> try ast.literal_eval,
                #                               then json.dumps
                #   - everything else      -> str()
                if isinstance(obs_out, (dict, list)):
                    obs_str = json.dumps(
                        obs_out, ensure_ascii=False, default=str
                    )
                elif isinstance(obs_out, str) and obs_out.lstrip().startswith(
                    ("{", "[")
                ):
                    stripped = obs_out.strip()
                    try:
                        parsed = ast.literal_eval(stripped)
                        if isinstance(parsed, (dict, list)):
                            obs_str = json.dumps(
                                parsed, ensure_ascii=False, default=str
                            )
                        else:
                            obs_str = str(obs_out)
                    except (ValueError, SyntaxError):
                        obs_str = str(obs_out)
                else:
                    obs_str = str(obs_out)

                is_tool_error = bool(
                    event.payload.get("is_error") or event.payload.get("error")
                )

                await _sync_and_dispatch_artifacts(curr_step)

                # Try to recover the tool name from the event payload.
                # peldrun-core may or may not include it depending on
                # the version; this is best-effort. The frontend no
                # longer requires it (see `extractOperationFromSteps`),
                # but carrying it makes the UI able to group steps more
                # precisely.
                observation_tool = str(
                    event.payload.get("tool_name")
                    or event.payload.get("tool")
                    or event.payload.get("toolName")
                    or ""
                )

                # Image-search detection: parse the image_search tool's
                # output and emit a dedicated IMAGE_RESULTS event so the
                # frontend can render a visual gallery. Best-effort; a
                # parse failure has no effect on the text observation.
                #
                # The observation's tool name may be either:
                #   * "image_search" — when the agent directly invoked
                #     the image search tool, or
                #   * "web_search"   — when the agent invoked the web
                #     search tool but the query had image intent, in
                #     which case web_search transparently routed to
                #     image_search internally and returned its payload
                #     unchanged (including the detailed "**Image URL:**"
                #     markdown format that _parse_image_search_observation
                #     expects).
                #
                # We cannot rely on `observation_tool` to gate the
                # parser: peldrun-core does NOT guarantee that
                # `EventType.OBSERVATION` carries a `tool_name` field.
                # On the current version, `event.payload` contains
                # only `output` / `error` — no tool name. That means
                # an `observation_tool in ("image_search", "web_search")`
                # check would NEVER match in production, silently
                # skipping gallery emission.
                #
                # Instead, we always attempt to parse the observation
                # output. The parser is a strict gate: it returns []
                # unless the text contains the exact "**Image URL:**"
                # markers that image_search emits. Arbitrary markdown
                # text cannot accidentally trigger a spurious
                # IMAGE_RESULTS event.
                if not is_tool_error:
                    try:
                        _parsed_images = _parse_image_search_observation(
                            obs_str
                        )
                        if _parsed_images:
                            from omweb.routers.image_proxy_rtr import (
                                build_proxy_url as _build_proxy_url,
                            )

                            _proxied: List[Dict[str, Any]] = []
                            for _img in _parsed_images:
                                # Detect already-proxied URLs (emitted by
                                # image_search when auto_download is on).
                                # Re-wrapping them would produce a nested
                                # proxy URL that the SSRF guard rejects.
                                _raw_img = _img["image_url"]
                                if _is_proxy_url(_raw_img):
                                    _pu = _extract_proxy_path(_raw_img)
                                else:
                                    _pu = _build_proxy_url(
                                        _raw_img, _img.get("source")
                                    )

                                _pt: Optional[str] = None
                                _raw_thumb = _img.get("thumbnail_url")
                                if _raw_thumb:
                                    if _is_proxy_url(_raw_thumb):
                                        _pt = _extract_proxy_path(_raw_thumb)
                                    else:
                                        _pt = _build_proxy_url(
                                            _raw_thumb, _img.get("source")
                                        )

                                _proxied.append(
                                    {
                                        "title": _img["title"],
                                        "image_url": _pu,
                                        "thumbnail_url": _pt,
                                        "source_url": _img.get("source_url"),
                                        "width": _img.get("width"),
                                        "height": _img.get("height"),
                                        "source": _img.get("source"),
                                    }
                                )
                            if _proxied:
                                await dispatch_event(
                                    job_id,
                                    SSEEvent(
                                        type=SSEEventType.IMAGE_RESULTS,
                                        step=curr_step,
                                        data={
                                            "query": _extract_query_from_observation(
                                                obs_str
                                            )
                                            or "",
                                            "provider": _extract_provider_from_observation(
                                                obs_str
                                            )
                                            or "unknown",
                                            "images": _proxied,
                                            "count": len(_proxied),
                                            "latency_ms": 0.0,
                                            "estimated_cost_usd": 0.0,
                                        },
                                    ),
                                )
                                # Accumulate for injection into the final
                                # result text so the gallery renders inside
                                # the deliverable bubble and survives a
                                # page refresh.
                                collected_proxied_images.extend(_proxied)
                                if not collected_images_query:
                                    collected_images_query = (
                                        _extract_query_from_observation(obs_str)
                                        or ""
                                    )
                                if collected_images_provider == "unknown":
                                    collected_images_provider = (
                                        _extract_provider_from_observation(obs_str)
                                        or "unknown"
                                    )
                    except Exception as _img_exc:
                        logger.debug(
                            "[ENGINE PELDRUN] Image extraction failed "
                            "for job %s: %s",
                            job_id,
                            _img_exc,
                        )

                # [RESOURCE-MONITOR-FIX] Close the tool-call span that
                # was opened on the matching TOOL_CALL event. Lookup
                # order:
                #   1. tool_call_id from the payload (exact match)
                #   2. tool_name from the payload (works for peldrun
                #      versions that only send the name)
                #   3. the oldest pending span (last-resort safety net
                #      so a provider that omits both fields cannot leak
                #      spans forever)
                if _monitor is not None:
                    try:
                        _obs_tc_id = str(
                            event.payload.get("tool_call_id") or ""
                        )
                        _span_id = None
                        _match_key = None
                        if _obs_tc_id and _obs_tc_id in _active_tool_spans:
                            _match_key = _obs_tc_id
                            _span_id = _active_tool_spans.get(_obs_tc_id)
                        elif (
                            observation_tool
                            and observation_tool in _active_tool_spans
                        ):
                            _match_key = observation_tool
                            _span_id = _active_tool_spans.get(
                                observation_tool
                            )
                        elif _active_tool_spans:
                            _match_key = next(iter(_active_tool_spans))
                            _span_id = _active_tool_spans.get(_match_key)

                        if _span_id is not None:
                            _monitor.end_span(
                                span_id=_span_id,
                                status=(
                                    _SpanStatus.FAILED
                                    if is_tool_error
                                    else _SpanStatus.COMPLETED
                                ),
                            )
                            # Remove every key that maps to this span
                            # so the secondary tool_name index cannot
                            # double-close it on the next observation.
                            _stale_keys = [
                                k
                                for k, v in _active_tool_spans.items()
                                if v == _span_id
                            ]
                            for _k in _stale_keys:
                                _active_tool_spans.pop(_k, None)
                    except Exception as _ep_exc:
                        logger.debug(
                            "[RESOURCE-MONITOR] end_span failed for "
                            "tool %s (job %s): %s",
                            observation_tool or "<unknown>",
                            job_id,
                            _ep_exc,
                        )

                # [FIX-SEQ-COLLISION] Bump the sequence counter one more
                # time before dispatching the OBSERVATION event.
                #
                # Background:
                #   `_sync_and_dispatch_artifacts` (called a few lines
                #   above) declares `nonlocal event_seq` and increments
                #   `event_seq` once for EVERY newly discovered artifact,
                #   using the incremented value as that artifact's `seq`.
                #   When at least one artifact was found, `event_seq`
                #   therefore already equals the `seq` of the LAST
                #   artifact_created event.
                #
                #   Without this extra increment, the OBSERVATION event
                #   below would carry the SAME `seq` as the last
                #   artifact_created event. Downstream consumers
                #   (`streaming.py`) deduplicate by strict `<=`
                #   comparison against `max_seen_sequence`, so the
                #   observation would be silently dropped from both the
                #   SSE stream AND the persisted `session.json`.
                #
                # Observed impact before the fix:
                #   * Tools that create files (`str_replace_editor`,
                #     `bash` with `touch`, code generators, ...) lost
                #     their OBSERVATION events entirely.
                #   * Tools that do NOT touch the filesystem (`mkdir`,
                #     `curl`, ...) kept theirs, producing the exact
                #     asymmetry documented in the bug report.
                #
                # The increment is unconditional (even when no artifacts
                # were found) so the observation always has a strictly
                # greater `seq` than every event dispatched before it in
                # this handler. A skipped number in the sequence is
                # harmless: the SSE consumer only requires strict
                # monotonicity, never density.
                event_seq += 1

                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.OBSERVATION,
                        step=curr_step,
                        data={
                            "output": obs_str,
                            "content": obs_str,
                            # Field name kept as `tool_name` (snake_case)
                            # because that is the shape produced by every
                            # other dispatch site in this engine. The
                            # companion fix in `streaming.py` teaches the
                            # SSE persister to read `tool_name` directly
                            # instead of guessing between `toolName` and
                            # `name` (the latter caused the persisted
                            # `toolName` to be a filename in
                            # `artifact_created` events).
                            "tool_name": observation_tool,
                            "is_error": is_tool_error,
                            "error": event.payload.get("error") if is_tool_error else None,
                            "seq": event_seq,
                            "model": model_name,
                        },
                    ),
                )

            elif event.type == EventType.ERROR:
                # [FIX] AgentRunner (in peldrun/engine/runner.py) emits
                # EventType.ERROR with payload = {"error": "", "message":
                # "<actual text>", "error_type": ..., ...} — the actual
                # error text lives in "message", NOT "error". Reading
                # only "error" yields an empty string because the key
                # exists (with an empty value), so `.get("error",
                # "Runtime Error")` returns "" not the default.
                #
                # [FIX-FORMAT] The raw payload is a Python dict dump
                # (e.g. `Error code: 400 - {'error': {'code':
                # 'invalid_request_error', ...}}`) which is unreadable
                # in the UI. We apply `format_smart_error` here so the
                # frontend receives a clean markdown error card (OOM,
                # credit balance, provider not responding, etc.)
                # instead of the raw string.
                #
                # Note: this path fires BEFORE the FAILED branch below,
                # so it is the FIRST terminal event the client sees.
                # Once the client receives it, `runStreamManager`
                # marks the stream terminal and ignores any later
                # ERROR event — meaning the FAILED branch's own
                # formatted message NEVER reaches the UI. This is
                # precisely why the raw text was showing up in the
                # user's screenshots despite the FAILED branch
                # already being formatted.
                raw_err_msg = str(
                    event.payload.get("error")
                    or event.payload.get("message")
                    or "Runtime Error"
                )
                if raw_err_msg and raw_err_msg.strip():
                    # Format the raw provider exception into a friendly
                    # markdown card. Falls back to the raw text if
                    # formatting itself raises for any reason.
                    try:
                        from omweb.agent_bridge_parts.errors import (
                            format_smart_error as _fmt_err,
                        )
                        err_msg = _fmt_err(
                            Exception(raw_err_msg),
                            model_name,
                            provider_name,
                        )
                    except Exception:
                        err_msg = raw_err_msg

                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.ERROR,
                            step=curr_step,
                            data={
                                "message": err_msg,
                                "content": err_msg,
                                "seq": event_seq,
                                "model": model_name,
                            },
                        ),
                    )

        async def _ordered_event_consumer() -> None:
            while True:
                event = await event_queue.get()
                if event is None:
                    event_queue.task_done()
                    break
                try:
                    await _process_single_core_event(event)
                except Exception as ex:
                    logger.error(
                        f"[ENGINE PELDRUN ERROR] Consumer failed for job {job_id}: {ex}",
                        exc_info=True,
                    )
                finally:
                    event_queue.task_done()

        consumer_task = asyncio.create_task(_ordered_event_consumer())

        async def _on_core_event(evt: PeldrunEvent) -> None:
            await event_queue.put(evt)

        # 6. Delegate Execution to Core Authority
        try:
            run_result = await core_executor.execute(
                request=run_request,
                event_listener=_on_core_event,
                custom_tools=adapted_core_tools,
            )

            await _sync_and_dispatch_artifacts(run_result.total_steps or current_core_step)
            await event_queue.put(None)
            await consumer_task

            # ── Post-run auth check ───────────────────────────────
            # If a lazy MCP auth failure occurred during the run, the
            # MCP tool executor has already:
            #   1. Recorded the failure in mcp_auth_state.
            #   2. Emitted the mcp_auth_required SSE event (modal opens).
            #   3. Called job_manager.fail_job with the correct message.
            #   4. Signalled core_executor.cancel (best-effort).
            #
            # Our only responsibility here is to NOT overwrite that
            # failure with a successful completion. We simply return.
            from omweb.extensions.mcp_auth_state import pop_auth_required

            _auth_flag = pop_auth_required(job_id)
            if _auth_flag:
                logger.info(
                    "[MCP AUTH] Job %s terminated due to lazy auth "
                    "requirement for server '%s' (chat=%s)",
                    job_id,
                    _auth_flag.get("server_id"),
                    _auth_flag.get("chat_id"),
                )
                return

        except asyncio.CancelledError:
            core_executor.cancel(job_id)
            try:
                await event_queue.put(None)
                await asyncio.wait_for(consumer_task, timeout=1.0)
            except Exception:
                consumer_task.cancel()
            print(f"[ENGINE PELDRUN] Task cancelled by operator for job: {job_id}")

            # ------------------------------------------------------------------
            # [M8.2-CANCEL] Emit a proper CANCELLED event BEFORE re-raising.
            #
            # Pre-M8.2 behavior: the engine re-raised CancelledError, the
            # dispatcher synthesized a bare CANCELLED event with
            # ``{"message": "Execution cancelled."}``. Because the event
            # carried no ``result`` field, the frontend fell back to
            # displaying the last CONTENT delta it had received — often a
            # 20-character fragment mid-word (e.g. ``ism Russia overview".``).
            # That fragment looked like an answer; the user thought the
            # run failed silently.
            #
            # The fix: complete the job with a dedicated cancellation
            # message that embeds the accumulated reasoning so the user
            # sees WHY the run stopped and WHAT the model was doing when
            # it did. The CANCELLED event carries the same message in
            # its ``result`` field so the frontend displays it verbatim.
            #
            # The completion here does NOT use ``job_manager.fail_job``
            # because cancellation is not a failure — the run terminated
            # cleanly on operator request. ``complete_job`` marks the job
            # as "completed" with a result; the streaming layer maps the
            # CANCELLED event to ``status="cancelled"`` on the session,
            # so the final stored state is "cancelled" (correct).
            # ------------------------------------------------------------------
            try:
                cancellation_message = (
                    f"### ⏹️ Execution cancelled by operator\n\n"
                    f"The run was stopped at step {current_core_step}. "
                    f"Partial output below."
                )
                partial_text = (
                    accumulated_content or latest_meaningful_thought
                )
                if partial_text and partial_text.strip():
                    # Cap at 2000 chars to avoid unbounded stored payloads
                    # from runaway reasoning loops.
                    thought_snippet = partial_text.strip()[:2000]
                    cancellation_message += (
                        "\n\n**Partial output before cancellation:**\n\n"
                        f"> {thought_snippet}"
                    )

                job_manager.complete_job(job_id, cancellation_message)

                if not terminal_dispatched:
                    terminal_dispatched = True
                    await dispatch_event(
                        job_id,
                        SSEEvent(
                            type=SSEEventType.CANCELLED,
                            step=current_core_step,
                            data={
                                "message": "Execution cancelled by operator.",
                                "result": cancellation_message,
                                "model": model_name,
                                "engine": self.engine_id,
                            },
                        ),
                    )
            except Exception as cancel_err:
                logger.debug(
                    "[ENGINE PELDRUN] Failed to emit cancellation for job "
                    "%s: %s",
                    job_id,
                    cancel_err,
                )

            raise

        except Exception as exc:
            try:
                await event_queue.put(None)
                await asyncio.wait_for(consumer_task, timeout=1.0)
            except Exception:
                consumer_task.cancel()

            err_msg = f"Task execution interrupted: {exc}"
            print(f"[ENGINE PELDRUN ERROR] {err_msg}")
            job_manager.fail_job(job_id, err_msg)
            if not terminal_dispatched:
                terminal_dispatched = True
                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.ERROR,
                        step=current_core_step,
                        data={
                            "message": err_msg,
                            "model": model_name,
                            "seq": event_seq + 1,
                        },
                    ),
                )
            return

        # 7. Extract Telemetry & Usage Metrics
        diag_data = run_result.metadata.get("diagnostics", {})
        inp_tok = int(diag_data.get("total_input_tokens") or 0)
        out_tok = int(diag_data.get("total_output_tokens") or 0)
        tot_tok = int(diag_data.get("total_tokens") or (inp_tok + out_tok))
        cost_nano = int(diag_data.get("total_cost_nano_usd") or 0)
        cost_usd = round(cost_nano / NANO_USD_PER_USD, 6)

        turn_id = f"turn_{int(time.time())}"
        turn_usage_dict = {
            "turn_id": turn_id,
            "prompt_tokens": inp_tok,
            "completion_tokens": out_tok,
            "total_tokens": tot_tok,
            "cached_input_tokens": diag_data.get("total_cached_tokens"),
            "reasoning_output_tokens": diag_data.get("total_reasoning_tokens"),
            "cost_usd": cost_usd,
            "cost_nano_usd": cost_nano,
            "latency_ms": diag_data.get("total_duration_ms"),
            "tokens_per_second": diag_data.get("overall_tokens_per_second"),
            "model": model_name,
            "provider": provider_name,
        }

        # [FIX-5.4] Forward the resolved file references (if any) into the
        # persisted turn record. `context.context_refs` is populated by the
        # dispatcher after mention resolution, and is None when the user did
        # not reference any workspace file for this turn.
        session_usage_summary = project_manager.record_turn_usage(
            chat_id=chat_id,
            turn_id=turn_id,
            turn_usage=turn_usage_dict,
            project_id=workspace_ctx.project_id or "default_project",
            context_refs=context.context_refs,
        )

        all_created = sorted([p for p in known_artifact_paths if p not in files_baseline])
        canonical_deliverables = all_created
        step_count = run_result.total_steps if run_result.total_steps > 0 else current_core_step

        if run_result.status == RunStatus.FAILED:
            raw_err = run_result.error or "Execution failed before reaching completion."
            print(f"[ENGINE PELDRUN] Job {job_id} terminated as FAILED in step {step_count}: {raw_err}")
            job_manager.fail_job(job_id, raw_err)
            if not terminal_dispatched:
                terminal_dispatched = True
                # Format the raw provider exception into a friendly
                # markdown error card (OOM, credit balance, provider
                # not responding, etc.) before sending to the client.
                # Falls back to the raw string if formatting fails.
                try:
                    from omweb.agent_bridge_parts.errors import format_smart_error as _fmt
                    err_msg = _fmt(Exception(raw_err), model_name, provider_name)
                except Exception:
                    err_msg = raw_err
                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.ERROR,
                        step=step_count,
                        data={
                            "message": err_msg,
                            "model": model_name,
                            "engine": self.engine_id,
                            "produced_files": canonical_deliverables,
                            "usage": turn_usage_dict,
                            "usage_summary": session_usage_summary,
                            "seq": event_seq + 1,
                        },
                    ),
                )
            return

        if run_result.status == RunStatus.CANCELLED:
            cancel_msg = run_result.error or "Execution was cancelled by operator."
            print(f"[ENGINE PELDRUN] Job {job_id} terminated as CANCELLED in step {step_count}")
            job_manager.fail_job(job_id, cancel_msg)
            if not terminal_dispatched:
                terminal_dispatched = True
                await dispatch_event(
                    job_id,
                    SSEEvent(
                        type=SSEEventType.ERROR,
                        step=step_count,
                        data={
                            "message": cancel_msg,
                            "model": model_name,
                            "engine": self.engine_id,
                            "status": "cancelled",
                            "seq": event_seq + 1,
                        },
                    ),
                )
            return

        # Compose the final message shown to the user.
        #
        # The previous implementation replaced the agent's own output
        # with a generic "Deliverables Created Successfully" block
        # whenever any file appeared in the workspace. For source
        # control this silently dropped the operation IDs, approval
        # IDs, and PR URLs the agent had reported — exactly the data
        # the user needs to complete the approval workflow. The fix
        # preserves the agent's output as the primary message and
        # only falls back to the deliverables block when the agent
        # produced no meaningful output of its own.
        # Prefer the accumulated streamed content over the raw
        # `run_result.output`. Background: agent mode streams content
        # through `EventType.CHUNK`, which is independent of the
        # reasoning channel (`latest_meaningful_thought`). When the
        # provider is non-reasoning (GigaChat, Llama, Mistral, ...) the
        # reasoning channel is empty, so falling back to it would
        # produce either an empty message or a stray reasoning
        # fragment. `accumulated_content` is the authoritative source.
        # [FIX-STRIP-TRAILING-TOOL-CALL] Remove a trailing
        # "Now calling <tool> as requested" + JSON block that some
        # models (notably GigaChat-3-Pro) append AFTER writing a
        # useful summary, right before invoking the tool for real.
        #
        # Without this strip, when the branch logic below prefers
        # `streamed_fallback` over `agent_output` (which is exactly
        # the fix for the "answer was wiped" bug), the user would
        # see the JSON block at the bottom of the final bubble. The
        # block is noise — the real tool call already happened.
        #
        # The strip is applied BEFORE `sanitize_final_result_text`
        # so the fallback argument passed to that helper is clean.
        streamed_fallback = _strip_trailing_tool_call_block(
            accumulated_content or latest_meaningful_thought
        )
        agent_output = sanitize_final_result_text(
            run_result.output, streamed_fallback
        )

        # Ignore generic success strings emitted by the terminate tool so
        # the UI does not display redundant "Task execution finished..." text.
        _GENERIC_STRINGS = {
            "task execution finished with status: success",
            "task execution finished",
            "task completed successfully",
            "task completed.",
            "task execution finished with status: success.",
            "task execution finished with status: failure",
            "task terminated with status: failure",
            "done",
            "task complete",
            "completed",
            "success",
            "ok",
        }
        _normalized = (agent_output or "").strip().lower()
        agent_output_is_meaningful = bool(
            agent_output
            and agent_output.strip()
            and _normalized not in _GENERIC_STRINGS
            # [FIX-TOOL-CALL-LEAK] Reject tool-call syntax that leaked
            # into ``run_result.output`` instead of being invoked.
            # Without this check, a fallback path that surfaces a
            # malformed ``terminate(status="success", message="``
            # would win over a large streamed answer that the user
            # already watched being generated.
            and not _looks_like_tool_call_leak(agent_output)
        )

        # [FIX-ACCUMULATED-CONTENT-FALLBACK] The pre-fix logic discarded
        # `streamed_fallback` whenever `run_result.output` was non-empty
        # but generic. Real-world failure (job_4bc33f8fd493): the
        # terminate tool returned "Task execution finished with status:
        # success", `run_result.output` was non-empty → the sanitizer
        # kept it → the meaningful check correctly rejected it as
        # generic → but the final branch assigned `result_text =
        # agent_output` again, i.e. the generic string. The accumulated
        # streamed content (which the user watched appear on screen for
        # several seconds) was silently discarded.
        #
        # New behavior: whenever `agent_output` is not meaningful
        # (empty OR generic), prefer `streamed_fallback` if IT is
        # meaningful. Only fall through to deliverables or the raw
        # generic string when neither side produced real content.
        _streamed_normalized = (streamed_fallback or "").strip().lower()
        streamed_is_meaningful = bool(
            streamed_fallback
            and streamed_fallback.strip()
            and _streamed_normalized not in _GENERIC_STRINGS
            # [FIX-TOOL-CALL-LEAK] Same rationale as the agent_output
            # side: a streamed buffer that ends up containing only the
            # tool-call fragment must not be selected as the final
            # answer. It would appear as garbage in the deliverable
            # bubble.
            and not _looks_like_tool_call_leak(streamed_fallback)
        )

        # [FIX-PRESERVE-STREAMED] Precedence rules when BOTH sources
        # produced meaningful text:
        #
        #   * If the streamed content is clearly richer than the
        #     terminate summary (>= 1.5x length), prefer the streamed
        #     content. The user WATCHED it being generated during the
        #     run — replacing it with a shorter terminate confirmation
        #     looks like the answer shrank on completion.
        #
        #   * Otherwise, prefer the terminate summary. It is clean,
        #     concise, and deliberately chosen by the model as the
        #     closing message. When the two are roughly equivalent,
        #     the shorter / cleaner one is the better UX.
        #
        # Real-world failure mode this fixes (job_d8f686c39f15 class):
        #   Step 4 streamed a ~700-char summary through CHUNK events
        #   that the user watched appear in real time. Step 5 then
        #   invoked terminate with a ~130-char recap. The pre-fix
        #   logic always preferred `agent_output` (the terminate
        #   message), silently discarding the 700-char answer the
        #   user had just finished reading. Visually the answer
        #   "shrank" on completion, which looked like a data-loss bug.
        if agent_output_is_meaningful and streamed_is_meaningful:
            streamed_len = len((streamed_fallback or "").strip())
            agent_len = len((agent_output or "").strip())
            if streamed_len >= agent_len * 1.5:
                result_text = streamed_fallback
                logger.info(
                    "[ENGINE PELDRUN] Preferring streamed content "
                    "(%d chars) over terminate summary (%d chars) "
                    "for job %s — preserving the richer answer the "
                    "user watched being generated.",
                    streamed_len,
                    agent_len,
                    job_id,
                )
            else:
                result_text = agent_output
                logger.info(
                    "[ENGINE PELDRUN] Using terminate summary "
                    "(%d chars) over streamed content (%d chars) "
                    "for job %s — the two are roughly equivalent, "
                    "and the terminate message is the model's "
                    "chosen closing text.",
                    agent_len,
                    streamed_len,
                    job_id,
                )
        elif agent_output_is_meaningful:
            # The agent produced a meaningful message. Keep it as the
            # final result.
            result_text = agent_output
        elif streamed_is_meaningful:
            # [FIX-ACCUMULATED-CONTENT-FALLBACK] run_result.output was
            # generic but the user watched meaningful content stream
            # through CHUNK events. Use that accumulated content so the
            # final message reflects what the user actually saw.
            result_text = streamed_fallback
            logger.info(
                "[ENGINE PELDRUN] Using accumulated streamed content "
                "(%d chars) as final result for job %s (run_result "
                "output was generic).",
                len(streamed_fallback or ""),
                job_id,
            )
        elif canonical_deliverables:
            # The agent produced no meaningful message; fall back to
            # the deliverables block so the user still knows what was
            # created. This matches the historical behavior for
            # agents that only produce files (e.g. code generators)
            # and terminate without a summary.
            file_bullets = "\n".join(
                [f"- `{f}`" for f in canonical_deliverables]
            )
            result_text = (
                f"### Deliverables Created Successfully\n\n"
                f"The requested project files have been built and "
                f"saved in your workspace:\n\n"
                f"{file_bullets}\n\n"
                f"You can preview and interact with the application "
                f"live in the **Preview** panel."
            )
        else:
            # Neither the agent nor the streamed content produced
            # meaningful text, and there are no deliverables. This is
            # the "everything empty" corner case.
            #
            # Historical behavior: surface whatever ``agent_output``
            # held — even a malformed tool-call fragment. The user
            # then saw ``terminate(status="success", message="`` as
            # the entire answer, which is exactly the failure this
            # fix set out to eliminate.
            #
            # New behavior:
            #   * If the retained text is a tool-call leak, replace it
            #     with an honest diagnostic so the user understands
            #     the run completed but produced no readable output.
            #   * Otherwise preserve the raw text for backward
            #     compatibility — some agents legitimately terminate
            #     with a bare string like "done", and replacing it
            #     with a synthetic message would be a regression.
            if _looks_like_tool_call_leak(agent_output):
                logger.warning(
                    "[ENGINE PELDRUN] Detected tool-call leak in the "
                    "final output for job %s: %r. Replacing with a "
                    "diagnostic message.",
                    job_id,
                    (agent_output or "")[:120],
                )
                result_text = (
                    "### Execution completed\n\n"
                    "The agent finished the task but produced no "
                    "readable output. Check the raw trace for "
                    "details, or regenerate the response."
                )
            else:
                result_text = agent_output

        # Inject any collected image results as an ``image_gallery``
        # markdown block. MarkdownRenderer turns this into an inline
        # gallery that renders INSIDE the ChatDeliverable bubble. Persisted
        # to disk via job_manager.complete_job, so it survives a page
        # refresh — the frontend cannot reconstruct proxy URLs on its own.
        if collected_proxied_images:
            try:
                import json as _json_mod

                _gallery_payload = _json_mod.dumps(
                    {
                        "images": collected_proxied_images,
                        "query": collected_images_query,
                        "provider": collected_images_provider,
                    },
                    ensure_ascii=False,
                )
                result_text = (
                    result_text
                    + f"\n\n```image_gallery\n{_gallery_payload}\n```\n"
                )
            except Exception as _gal_err:
                logger.debug(
                    "[ENGINE PELDRUN] Failed to append image_gallery "
                    "block for job %s: %s",
                    job_id,
                    _gal_err,
                )

        print(
            f"[ENGINE PELDRUN] Job {job_id} completed successfully in step {step_count}. "
            f"Tokens: {tot_tok} | Cost: ${cost_usd}"
        )

        job_manager.complete_job(job_id, result_text)

        # 8. Atomically Synchronize Context Sidecar after task conclusion
        try:
            chat_storage_engine.sync_sidecar(chat_id, model_id=model_name)
        except Exception as sidecar_err:
            logger.debug(f"[ENGINE PELDRUN] Sidecar synchronization notice: {sidecar_err}")

        if not terminal_dispatched:
            terminal_dispatched = True
            await dispatch_event(
                job_id,
                SSEEvent(
                    type=SSEEventType.FINAL,
                    step=step_count,
                    data={
                        "result": result_text,
                        "model": model_name,
                        "engine": self.engine_id,
                        "produced_files": canonical_deliverables,
                        "usage": turn_usage_dict,
                        "usage_summary": session_usage_summary,
                        "cost_usd": cost_usd,
                        "seq": event_seq + 1,
                    },
                ),
            )
