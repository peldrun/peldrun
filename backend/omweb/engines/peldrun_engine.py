        event_queue: asyncio.Queue[Optional[PeldrunEvent]] = asyncio.Queue()
        event_seq: int = 0
        current_core_step: int = 1
        is_first_step_start: bool = True
        terminal_dispatched: bool = False
        # Accumulators for image results captured during this run. They
        # are injected into the final result text as an ``image_gallery``
        # markdown block so the frontend renders the gallery INSIDE the
