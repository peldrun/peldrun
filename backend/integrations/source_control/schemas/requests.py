class CreateOperationRequest(BaseSCRequest):
    """Payload to register a new durable source control workflow operation."""

    operation_type: str = Field(
        ...,
        description="Type of operation (e.g. 'push_branch', 'create_change_request').",
    )
    repository_id: str = Field(
        ...,
        min_length=1,
        max_length=256,
        description="Target repository identifier (numeric ID or slug).",
    )
    target_branch: str = Field(
        ...,
        min_length=1,
        max_length=200,
        description="Destination branch for the proposed changes.",
    )
    workspace_id: Optional[str] = Field(
        default=None,
        description="Optional isolated local workspace ID bound to this operation.",
    )
    title: Optional[str] = Field(
        default=None,
        max_length=300,
        description="Proposed title for change requests or commit messages.",
    )
    description: Optional[str] = Field(
        default=None,
        max_length=10000,
        description="Proposed description or rationale for changes.",
    )
    provider: str = Field(
        default="github",
        description="Target source control provider identifier.",
    )

    @field_validator("operation_type")
    @classmethod
    def validate_op_type(cls, v: str) -> str:
        """
        Normalize and validate the operation type.

        The set of allowed values mirrors the operation kinds the
        application actually dispatches through the source-control
        dispatcher (see ``SourceControlTool._ACTION_MAP``), not just
        the three remote-write kinds that were originally hard-coded.
        Both local operations (``create_workspace``, ``create_branch``,
        ``inspect_diff``, ``run_checks``) and remote-write operations
        (``push_branch``, ``create_change_request``,
        ``merge_change_request``, ``request_approval``) are accepted so
        that callers can register a durable operation of any of these
        kinds.

        The dispatch layer is still responsible for refusing an
        operation whose kind is not implemented — this validator only
        rejects clearly malformed values.
        """
        clean = v.strip().lower()
        allowed = {
            # Local operations
            "create_workspace",
            "create_branch",
            "inspect_diff",
            "run_checks",
            # Remote-write operations
            "request_approval",
            "push_branch",
            "create_change_request",
            "merge_change_request",
        }
        if clean not in allowed:
            raise ValueError(
                f"Invalid operation_type '{v}'. "
                f"Must be one of: {sorted(allowed)}"
            )
        return clean

    @field_validator("target_branch")
    @classmethod
    def validate_target(cls, v: str) -> str:
        return validate_branch_name(v)


